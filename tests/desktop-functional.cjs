const { _electron: electron } = require('playwright')
const path = require('path')
const fs = require('fs/promises')
const assert = require('node:assert/strict')

async function main() {
  const root = path.resolve(__dirname, '..')
  const dataDir = path.join(root, 'test-results', 'functional-data')
  await fs.rm(dataDir, { recursive: true, force: true })
  const env = { ...process.env, OQS_TEST_DATA: dataDir, OQS_USE_BUILD: '1' }
  delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ args: [root], executablePath: path.join(root, 'node_modules', 'electron', 'dist', 'electron.exe'), env })
  const errors = []
  try {
    const page = await app.firstWindow()
    page.on('pageerror', error => errors.push(error.message))
    await page.locator('.main-workspace').waitFor()
    await page.locator('header').getByRole('button', { name: '新建记录' }).click()
    assert.equal(await page.getByRole('button', { name: /定稿|开始测试|添加核心考点|提交预览|达成性评估/ }).count(), 0)
    await page.locator('#section-doubao .note-input').fill('先保存备注，即使问题和回复还没有填写。')
    await page.locator('.save-indicator').click()
    await page.locator('.save-indicator.saved').waitFor()
    await page.reload()
    await page.locator('#section-doubao .note-input').waitFor()
    assert.equal(await page.locator('#section-doubao .note-input').inputValue(), '先保存备注，即使问题和回复还没有填写。')
    await page.getByPlaceholder('记录标题').fill('故障恢复资料')
    const prompt = '生产数据库主从延迟时如何选择恢复方案？' + '保留详细背景条件。'.repeat(15)
    const criteria = '考点一：判断数据一致性风险。\n\n考点二：记录回切条件和操作顺序。\n附加原始文本：无需拆成单条考点。'
    await page.getByLabel('问题（Prompt）').fill(prompt)
    await page.getByLabel('关键洞察（Insight）').fill('第一段：先确定边界。\n\n第二段：随后选择方案。')
    await page.getByLabel('决定性核心考点', { exact: true }).fill(criteria)
    await page.getByLabel('非决定性核心考点', { exact: true }).fill('可选考点：补充说明与表达结构。')
    await page.getByLabel('问题类型', { exact: true }).selectOption('How-to 类')
    await page.getByLabel('标签', { exact: true }).fill('资料标签-可搜索')
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j2HsAAAAASUVORK5CYII=', 'base64')
    for (const [id, model, result] of [['doubao', '豆包专家', '未达成'], ['gpt', 'GPT-5.6-Sol', '达成'], ['opus', 'Opus 4.6', '']]) {
      await page.getByLabel(`${model}实际名称`, { exact: true }).fill(model)
      assert.equal(await page.getByLabel(`${model}模式`, { exact: true }).count(), 0)
      await page.getByLabel(`${model}总体结果`, { exact: true }).selectOption(result)
      await page.getByLabel(`${model}原始回复`, { exact: true }).fill(`# ${model}\n\n完整回复 **原文**。`)
      await page.getByLabel(`${model}达成性备注`, { exact: true }).fill(`${model}的独立备注。`)
      if (id === 'doubao') {
        const tray = page.locator('#section-doubao .image-tray')
        await tray.scrollIntoViewIfNeeded()
        const transfer = await page.evaluateHandle(({ base64 }) => {
          const dataTransfer = new DataTransfer()
          dataTransfer.items.add(new File([Uint8Array.from(atob(base64), char => char.charCodeAt(0))], 'doubao-dragged.png', { type: 'image/png' }))
          return dataTransfer
        }, { base64: png.toString('base64') })
        await tray.dispatchEvent('dragenter', { dataTransfer: transfer })
        await tray.dispatchEvent('dragover', { dataTransfer: transfer })
        await tray.locator('.drop-hint').waitFor()
        const dragHint = (await tray.locator('.drop-hint').textContent()).trim()
        await tray.dispatchEvent('drop', { dataTransfer: transfer })
        await transfer.dispose()
        assert.equal(dragHint, '松开即可导入图片')
      } else {
        await page.locator(`#section-${id} input[type=file]`).setInputFiles({ name: `${id}.png`, mimeType: 'image/png', buffer: png })
      }
      await page.locator(`#section-${id} .image-preview img`).waitFor()
      await page.waitForFunction(selector => { const img = document.querySelector(selector); return img?.complete && img.naturalWidth > 0 }, `#section-${id} .image-preview img`)
    }
    await page.getByLabel('验收结果', { exact: true }).selectOption('不通过')
    await page.getByLabel('豆包专家原始回复', { exact: true }).fill('更新后的回复')
    await page.getByLabel('决定性核心考点', { exact: true }).fill(`${criteria}\n最后的补充。`)
    assert.equal(await page.getByLabel('豆包专家达成性备注', { exact: true }).inputValue(), '豆包专家的独立备注。')
    assert.equal(await page.getByLabel('豆包专家总体结果', { exact: true }).inputValue(), '未达成')
    assert.equal(await page.getByLabel('验收结果', { exact: true }).inputValue(), '不通过')
    await page.locator('.save-indicator').click()
    await page.locator('.save-indicator.saved').waitFor()
    await page.reload()
    await page.getByPlaceholder('记录标题').waitFor()
    assert.equal(await page.getByLabel('决定性核心考点', { exact: true }).inputValue(), `${criteria}\n最后的补充。`)
    assert.equal(await page.getByLabel('问题（Prompt）').inputValue(), prompt)
    await page.getByLabel('搜索记录').fill('资料标签-可搜索')
    assert.equal(await page.locator('.record-item').count(), 1)
    await page.getByRole('button', { name: '清空搜索' }).click()
    await page.getByRole('button', { name: '记录文本', exact: true }).click()
    const text = await page.locator('.export-preview').innerText()
    assert.ok(text.includes(criteria))
    assert.ok(text.includes('更新后的回复'))
    assert.ok(text.includes('GPT-5.6-Sol的独立备注。'))
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click()
    const backupPath = path.join(root, 'test-results', 'full-backup.json')
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }) }, backupPath)
    await page.getByRole('button', { name: '导出备份', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '开始导出', exact: true }).click()
    await page.getByText(/^全部记录备份已导出，共 \d+ 条，包含完整文本和截图。$/).waitFor()
    const backup = JSON.parse(await fs.readFile(backupPath, 'utf8'))
    assert.equal(backup.version, 4)
    assert.equal(backup.records[0].nonDecisiveCriteriaText, '可选考点：补充说明与表达结构。')
    for (const id of ['doubao', 'gpt', 'opus']) assert.ok(backup.records[0].models[id].screenshots[0].dataUrl.startsWith('data:image/png;base64,'))
    const copy = structuredClone(backup.records[0]); copy.id = crypto.randomUUID(); copy.title = '导入副本'
    const importPath = path.join(root, 'test-results', 'import.json')
    await fs.writeFile(importPath, JSON.stringify({ version: 4, records: [backup.records[0], copy] }), 'utf8')
    await app.evaluate(({ dialog }, filePath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filePath] }) }, importPath)
    await page.getByRole('button', { name: '导入备份', exact: true }).click()
    await page.getByRole('button', { name: '合并导入' }).click()
    await page.getByText('已导入 1 条新记录，跳过 1 条同编号记录。').waitFor()
    await page.locator('.record-list').getByRole('button', { name: /导入副本/ }).click()
    await page.waitForFunction(() => [...document.querySelectorAll('.image-preview img')].every(img => img.complete && img.naturalWidth > 0))
    await page.getByRole('button', { name: '复制整条记录', exact: true }).click()
    assert.equal(await page.getByLabel('豆包专家达成性备注', { exact: true }).inputValue(), '豆包专家的独立备注。')
    assert.equal(await page.getByLabel('GPT-5.6-Sol原始回复', { exact: true }).inputValue(), '# GPT-5.6-Sol\n\n完整回复 **原文**。')
    await page.locator('.detail-scroll').evaluate(element => { element.scrollTop = 0 })
    await page.screenshot({ path: path.join(root, 'test-results', 'functional.png') })
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1120, 720))
    await page.screenshot({ path: path.join(root, 'test-results', 'narrow.png') })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    await page.getByPlaceholder('记录标题').fill('已验证关闭保存')
    const closed = page.waitForEvent('close')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
    await closed
    const saved = JSON.parse(await fs.readFile(path.join(dataDir, 'records.json'), 'utf8'))
    assert.equal(saved.version, 4)
    assert.ok(saved.records.some(record => record.title === '已验证关闭保存'))
    assert.equal(saved.records.length, 3)
    assert.deepEqual(errors, [])
    console.log('Free-form recording, independent fields, screenshots, backup/import, full duplication and close-save: passed')
  } finally { await app.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
