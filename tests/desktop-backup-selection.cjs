const { _electron: electron } = require('playwright')
const path = require('path')
const fs = require('fs/promises')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('url')
const { createStorage } = require('../electron/storage.cjs')

async function main() {
  const root = path.resolve(__dirname, '..')
  const dataDir = await fs.mkdtemp(path.join(root, 'test-results', 'backup-selection-'))
  const storage = createStorage(dataDir)
  const { createRecord, validateBackup, recordCompletion, MODELS } = await import(pathToFileURL(path.join(root, 'src', 'domain.js')).href)
  const png = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j2HsAAAAASUVORK5CYII='
  const image = { ...await storage.saveAttachment({ dataUrl: png, originalName: '完整截图.png' }), id: crypto.randomUUID(), name: '完整截图.png' }
  const records = Array.from({ length: 40 }, (_, index) => {
    const record = createRecord()
    Object.assign(record, { title: `导出测试记录 ${String(index + 1).padStart(2, '0')}`, archived: index % 2 === 1, type: 'How-to 类', prompt: `完整问题-${index}`, criteriaText: `决定性考点-${index}`, nonDecisiveCriteriaText: `非决定性考点-${index}` })
    for (const model of MODELS) Object.assign(record.models[model.id], { response: `完整 Markdown 回复-${index}-${model.id}`, screenshots: [structuredClone(image)] })
    if (index === 0) {
      record.insight = '完整洞察'; record.acceptanceResult = '通过'
      for (const model of MODELS) Object.assign(record.models[model.id], { note: '完整备注', result: '达成' })
    }
    return record
  })
  await storage.save({ version: 4, records })
  const env = { ...process.env, OQS_TEST_DATA: dataDir, OQS_USE_BUILD: '1' }
  delete env.ELECTRON_RUN_AS_NODE
  const packagedExecutable = process.env.OQS_TEST_EXECUTABLE
  const app = await electron.launch({ args: packagedExecutable ? [] : [root], executablePath: packagedExecutable || path.join(root, 'node_modules', 'electron', 'dist', 'electron.exe'), env })
  try {
    const page = await app.firstWindow()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.getByPlaceholder('记录标题').waitFor()
    await page.getByLabel('搜索记录').fill('无匹配结果')
    assert.equal(await page.locator('.record-item').count(), 0)
    const open = async () => {
      await page.getByRole('button', { name: '导出备份', exact: true }).click()
      const dialog = page.getByRole('dialog')
      await dialog.getByRole('radio', { name: '选择特定记录', exact: true }).check()
      assert.equal(await dialog.getByRole('checkbox').count(), 40)
      return dialog
    }
    let dialog = await open()
    const group = archived => dialog.getByRole('region', { name: archived ? '已归档记录' : '未归档记录', exact: true })
    const row = (archived, index) => group(archived).getByRole('checkbox').nth(index)
    const selected = () => dialog.locator('[role=checkbox][aria-checked=true]')
    const clear = () => dialog.getByRole('button', { name: '清空选择', exact: true }).click()
    const dragRows = async (from, to) => {
      const start = await from.boundingBox(), end = await to.boundingBox()
      await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
      await page.mouse.down()
      await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 8 })
      await page.mouse.up()
    }
    assert.equal(await dialog.getByRole('button', { name: '开始导出' }).isDisabled(), true)
    assert.equal(await group(false).getByRole('checkbox').count(), 20)
    assert.equal(await group(true).getByRole('checkbox').count(), 20)
    assert.match(await row(false, 0).locator('.backup-record-completion').innerText(), /完成度 100%[\s\S]*资料完整/)
    const partial = recordCompletion(records[2])
    assert.ok((await row(false, 1).locator('.backup-record-completion').innerText()).includes('完成度 ' + partial.percent + '%'))
    assert.ok((await row(false, 1).locator('.backup-record-completion').getAttribute('title')).includes('缺失：关键洞察'))
    await row(false, 0).click()
    assert.equal(await row(false, 0).getAttribute('aria-checked'), 'true')
    await row(false, 0).click()
    assert.equal(await selected().count(), 0)
    await row(false, 0).press('Space')
    assert.equal(await selected().count(), 1)
    await clear()
    await dragRows(row(false, 0), row(false, 2))
    assert.equal(await selected().count(), 3)
    await dragRows(row(false, 0), row(false, 2))
    assert.equal(await selected().count(), 0)
    await dragRows(row(false, 1), row(true, 1))
    assert.equal(await selected().count(), 2)
    await clear()

    // Moving below the list scrolls it and selects every skipped row in between.
    const list = group(false).locator('.backup-record-list')
    const first = await row(false, 0).boundingBox(), panel = await list.boundingBox()
    await page.mouse.move(first.x + 40, first.y + first.height / 2)
    await page.mouse.down()
    await page.mouse.move(panel.x + 40, panel.y + panel.height + 8, { steps: 4 })
    await page.waitForFunction(() => document.querySelector('[data-export-list=active]').scrollTop > 100)
    await page.mouse.up()
    const autoIds = await group(false).locator('[aria-checked=true]').evaluateAll(elements => elements.map(el => el.dataset.exportRecordId))
    assert.ok(autoIds.length > 3)
    assert.deepEqual(autoIds, records.filter(record => !record.archived).slice(0, autoIds.length).map(record => record.id))
    const scrollAfterUp = await list.evaluate(el => el.scrollTop)
    await page.mouse.move(10, 10)
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    assert.equal(await list.evaluate(el => el.scrollTop), scrollAfterUp)
    await clear()
    await group(false).getByRole('button', { name: '全选本组', exact: true }).click()
    assert.equal(await selected().count(), 20)
    await group(true).getByRole('button', { name: '全选本组', exact: true }).click()
    assert.equal(await selected().count(), 40)
    await clear()
    await dialog.getByRole('button', { name: '全选', exact: true }).click()
    assert.equal(await selected().count(), 40)
    await clear()

    await row(false, 0).scrollIntoViewIfNeeded()
    await row(false, 0).click()
    await row(true, 3).scrollIntoViewIfNeeded()
    await row(true, 3).click()
    await dialog.getByRole('radio', { name: '全部记录', exact: true }).check()
    assert.equal(await dialog.locator('.backup-summary').innerText(), '将导出 40 条记录。')
    await dialog.getByRole('radio', { name: '选择特定记录', exact: true }).check()
    assert.equal(await selected().count(), 2)
    await app.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }) })
    await dialog.getByRole('button', { name: '开始导出' }).click()
    await page.waitForFunction(() => !document.querySelector('.modal-actions .primary').disabled)
    assert.equal(await selected().count(), 2)

    const filePath = path.join(dataDir, 'selected-backup.json')
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }) }, filePath)
    await dialog.getByRole('button', { name: '开始导出' }).click()
    await page.getByText('选择特定记录备份已导出，共 2 条，包含完整文本和截图。', { exact: true }).waitFor()
    const backup = JSON.parse(await fs.readFile(filePath, 'utf8'))
    validateBackup(backup)
    const chosen = [records[0], records[7]]
    const expected = await storage.createBackup({ version: 4, records: chosen })
    assert.deepEqual(backup.records, expected.records)
    assert.deepEqual((await storage.load()).records, records)
    await import(pathToFileURL(path.join(root, '专家填写助手-v1.3.8-记录库兼容版', 'Chrome扩展', 'library-import.js')).href)
    assert.equal((await globalThis.QFRecordLibrary.convert(backup)).length, 2)

    // Cancel a drag while closing the modal; reopening starts a fresh selection.
    dialog = await open()
    assert.equal(await selected().count(), 0)
    const start = await row(false, 0).boundingBox()
    await page.mouse.move(start.x + 35, start.y + start.height / 2)
    await page.mouse.down()
    await page.keyboard.press('Escape')
    await page.mouse.up()
    assert.equal(await page.getByRole('dialog').count(), 0)
    await page.evaluate(() => window.desktopApi.saveSettings({ theme: 'dark', fontSize: 20 }))
    await page.reload()
    await page.getByPlaceholder('记录标题').waitFor()
    await page.waitForFunction(() => document.documentElement.dataset.fontSize === '20')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1120, 720))
    dialog = await open()
    await row(false, 0).click()
    assert.equal(await dialog.evaluate(element => element.scrollWidth > element.clientWidth), false)
    assert.equal(await dialog.getByRole('button', { name: '开始导出' }).evaluate(el => el.getBoundingClientRect().bottom <= window.innerHeight), true)
    await page.screenshot({ path: path.join(root, 'test-results', 'backup-selection-dark.png') })
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    await page.evaluate(() => window.desktopApi.saveSettings({ theme: 'light', fontSize: 14 }))
    await page.reload()
    await page.getByPlaceholder('记录标题').waitFor()
    await page.waitForFunction(() => document.documentElement.dataset.fontSize === '14')
    dialog = await open()
    await row(false, 0).click()
    await row(true, 0).click()
    await page.screenshot({ path: path.join(root, 'test-results', 'backup-selection.png') })
    assert.deepEqual(errors, [])
    console.log('Selected backup passed: click/keyboard, drag selection and removal, cross-group selection, edge auto-scroll, select-all, native cancel, exact selected records/images, plugin compatibility and themes.')
  } finally { await app.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
