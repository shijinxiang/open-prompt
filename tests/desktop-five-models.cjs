const { _electron: electron } = require('playwright')
const path = require('path')
const fs = require('fs/promises')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('url')
const { createStorage } = require('../electron/storage.cjs')

async function main() {
  const root = path.resolve(__dirname, '..')
  const dataDir = await fs.mkdtemp(path.join(root, 'test-results', 'five-models-'))
  const storage = createStorage(dataDir)
  const { createRecord, MODELS } = await import(pathToFileURL(path.join(root, 'src', 'domain.js')).href)
  const png = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j2HsAAAAASUVORK5CYII='
  const record = createRecord()
  delete record.models.model4; delete record.models.model5; delete record.quality
  record.title = '原三模型资料'; record.type = 'How-to 类'; record.prompt = '原问题'; record.insight = '原洞察'; record.criteriaText = '原考点整段文本'; record.acceptanceResult = '通过'; record.notes = '原补充备注'
  const image = { ...await storage.saveAttachment({ dataUrl: png, originalName: 'original.png' }), id: crypto.randomUUID(), name: 'original.png' }
  for (const [id, name] of [['doubao', '豆包专家'], ['gpt', 'GPT-5.6-Sol'], ['opus', 'Opus 4.6']]) Object.assign(record.models[id], { actualName: name, mode: '原模式', response: `原回复-${id}`, note: `原备注-${id}`, result: '达成', screenshots: [structuredClone(image)] })
  await storage.save({ version: 2, records: [record] })
  const originalBytes = await fs.readFile(storage.dataFile, 'utf8')
  const settings = { fontSize: 18 }
  await storage.saveSettings(settings)
  const env = { ...process.env, OQS_TEST_DATA: dataDir, OQS_USE_BUILD: '1' }
  delete env.ELECTRON_RUN_AS_NODE
  const options = { args: [root], executablePath: path.join(root, 'node_modules', 'electron', 'dist', 'electron.exe'), env }
  let app = await electron.launch(options)
  const errors = []
  try {
    let page = await app.firstWindow()
    page.on('pageerror', error => errors.push(error.message))
    await page.getByPlaceholder('记录标题').waitFor()
    assert.equal(await fs.readFile(path.join(dataDir, 'records-before-v4.json'), 'utf8'), originalBytes)
    const upgraded = await page.evaluate(() => window.desktopApi.loadData())
    assert.equal(upgraded.version, 4)
    for (const [key, value] of Object.entries(record)) {
      if (key === 'notes') { assert.equal(upgraded.records[0].notes, undefined); continue }
      if (key === 'models') { for (const id of Object.keys(value)) { const { mode, ...retained } = value[id]; assert.deepEqual(upgraded.records[0].models[id], retained) } }
      else assert.deepEqual(upgraded.records[0][key], value)
    }
    assert.deepEqual(JSON.parse(await fs.readFile(storage.settingsFile, 'utf8')), settings)
    assert.equal(await page.locator('.record-item-missing').count(), 0)
    assert.equal(await page.locator('.image-tray').count(), 3)
    await page.getByRole('switch', { name: '二轮资料', exact: true }).check()
    assert.equal(await page.locator('.image-tray').count(), 5)
    assert.equal(await page.getByLabel('模型4实际名称', { exact: true }).inputValue(), '')
    for (const model of MODELS) assert.equal(await page.getByLabel(`${model.name}模式`, { exact: true }).count(), 0)
    for (const label of ['模型4来源或系列', '模型5联网状态', '模型4Context 模式', '模型4采集与核验备注', '待核验与待补充材料', '五模型考点矩阵与证据', '补充备注']) assert.equal(await page.getByLabel(label, { exact: true }).count(), 0)
    assert.equal(await page.getByLabel('质检判断', { exact: true }).count(), 0)
    assert.equal(await page.getByLabel('审核结论', { exact: true }).count(), 0)
    assert.equal(await page.getByLabel('质检意见', { exact: true }).count(), 0)
    assert.equal(await page.getByLabel('专家返修备注', { exact: true }).count(), 0)
    await page.locator('.missing-notice summary').click()
    assert.doesNotMatch(await page.locator('.missing-fields').innerText(), /质检|审核|返修/)
    const imagePayload = { name: 'added-shot.png', mimeType: 'image/png', buffer: Buffer.from(png.split(',')[1], 'base64') }
    for (const [id, name, result] of [['model4', '自选模型甲', '达成'], ['model5', '自选模型乙', '未达成']]) {
      const label = id === 'model4' ? '模型4' : '模型5'
      await page.getByLabel(`${label}实际名称`, { exact: true }).fill(name)
      await page.getByLabel(`${label}原始回复`, { exact: true }).fill(`# ${name}\n\n**粗体**与 _强调_，以及\\*转义符\\*。  \n保留换行。\n\n- 第一项\n  - 嵌套列表\n\n| 列A | 列B |\n| --- | --- |\n| 内容 | 数值 |\n\n\`\`\`js\nconst value = "a\\nb";\n\tconsole.log(value);\n\`\`\`\n\n> 引用\n\n[链接](https://example.com)\n`)
      await page.getByLabel(`${label}总体结果`, { exact: true }).selectOption(result)
      await page.getByLabel(`${label}达成性备注`, { exact: true }).fill(`${name}的全部考点证据与分析。`)
      await page.locator(`#section-${id} input[type=file]`).setInputFiles(imagePayload)
      await page.locator(`#section-${id} .image-preview img`).waitFor()
    }
    await page.locator('.save-indicator').click()
    await page.locator('.save-indicator.saved').waitFor()
    const beforeCopy = await page.evaluate(() => window.desktopApi.loadData())
    for (const model of MODELS) {
      const section = page.locator(`#section-${model.id}`)
      const expected = await page.getByLabel(`${model.name}原始回复`, { exact: true }).inputValue()
      await section.getByRole('button', { name: `复制${model.name}回复`, exact: true }).click()
      await page.waitForFunction(async text => await navigator.clipboard.readText() === text, expected)
      const nativeText = await app.evaluate(async ({ clipboard }) => clipboard.readText())
      assert.equal(nativeText.replace(/\r\n/g, '\n'), expected)
      await section.getByRole('button', { name: 'Markdown 预览', exact: true }).click()
      await section.getByRole('button', { name: `复制${model.name}回复`, exact: true }).click()
      await page.waitForFunction(async text => await navigator.clipboard.readText() === text, expected)
      await section.getByRole('button', { name: '原文', exact: true }).click()
    }
    assert.deepEqual((await page.evaluate(() => window.desktopApi.loadData())).records, beforeCopy.records)
    await page.getByLabel('模型5原始回复', { exact: true }).fill('')
    assert.equal(await page.getByRole('button', { name: '复制模型5回复', exact: true }).isDisabled(), true)
    await page.getByLabel('模型5原始回复', { exact: true }).fill(beforeCopy.records[0].models.model5.response)
    const responseHeader = page.locator('#section-model4 .response-header')
    await responseHeader.scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(root, 'test-results', 'reply-copy-desktop.png') })
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1120, 800))
    await responseHeader.scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(root, 'test-results', 'reply-copy-narrow.png') })
    const bounds = await responseHeader.evaluate(header => {
      const label = header.querySelector('label').getBoundingClientRect()
      const tools = header.querySelector('.response-tools').getBoundingClientRect()
      return { labelRight: label.right, labelBottom: label.bottom, toolsLeft: tools.left, toolsTop: tools.top }
    })
    assert.ok(bounds.labelRight <= bounds.toolsLeft || bounds.labelBottom <= bounds.toolsTop)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1480, 960))
    const ranking = '模型1 = 模型3 ＞ 模型2 = 模型4 ＞ 模型5'
    await page.getByLabel('核心考点的达成性排序', { exact: true }).fill(ranking)
    await page.getByLabel('核心考点的达成性排序说明', { exact: true }).fill('总结：短说明也能保存。')
    await page.locator('.save-indicator').click()
    await page.locator('.save-indicator.saved').waitFor()
    assert.match(await page.locator('.record-item-missing').innerText(), /不足 300 字/)
    const explanation = ['总结：', '模型1：', '模型2：', '模型3：', '模型4：', '模型5：'].map(label => `${label}${'排序依据固定核心考点的达成集合，保留原始证据。'.repeat(4)}`).join('\n\n')
    await page.getByLabel('核心考点的达成性排序说明', { exact: true }).fill(explanation)
    assert.equal(await page.locator('.record-item-missing').count(), 0)
    assert.equal(await page.locator('.quality-warnings').count(), 0)
    await page.getByLabel('模型5实际名称', { exact: true }).fill('自选模型甲')
    assert.match(await page.locator('.quality-warnings').innerText(), /名称重复/)
    await page.getByLabel('模型5实际名称', { exact: true }).fill('自选模型乙')
    assert.equal(await page.locator('.quality-warnings').count(), 0)
    await page.getByRole('switch', { name: '二轮资料', exact: true }).uncheck()
    await page.locator('.save-indicator').click()
    await page.locator('.save-indicator.saved').waitFor()
    const disabled = await page.evaluate(() => window.desktopApi.loadData())
    assert.equal(disabled.records[0].models.model4.actualName, '自选模型甲')
    assert.equal(disabled.records[0].quality.ranking, ranking)
    assert.equal(await page.locator('.image-tray').count(), 3)
    await page.getByRole('switch', { name: '二轮资料', exact: true }).check()
    assert.equal(await page.getByLabel('核心考点的达成性排序说明', { exact: true }).inputValue(), explanation)
    await page.getByLabel('搜索记录').fill('自选模型乙')
    assert.equal(await page.locator('.record-item').count(), 1)
    await page.getByRole('button', { name: '清空搜索', exact: true }).click()
    await page.getByRole('button', { name: '记录文本', exact: true }).click()
    const text = await page.locator('.export-preview').innerText()
    assert.ok(text.includes(ranking)); assert.ok(text.includes('自选模型甲')); assert.ok(text.includes(explanation))
    assert.doesNotMatch(text, /质检判断|审核结论|质检意见|专家返修|待核验|矩阵|补充备注|联网状态|Context 模式|来源／系列/)
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click()
    await page.locator('#section-model4').getByRole('button', { name: /复制图片：/ }).click()
    await page.getByText('图片已复制，可直接粘贴。', { exact: true }).waitFor()
    const backupPath = path.join(dataDir, 'five-models-backup.json')
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }) }, backupPath)
    await page.getByRole('button', { name: '导出备份', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '开始导出', exact: true }).click()
    await page.getByText(/^全部记录备份已导出，共 \d+ 条，包含完整文本和截图。$/).waitFor()
    const backup = JSON.parse(await fs.readFile(backupPath, 'utf8'))
    assert.equal(backup.version, 4)
    for (const model of MODELS) assert.equal(backup.records[0].models[model.id].screenshots[0].dataUrl, png)
    const copy = structuredClone(backup.records[0]); copy.id = crypto.randomUUID(); copy.title = '导入五模型副本'
    const importPath = path.join(dataDir, 'import.json')
    await fs.writeFile(importPath, JSON.stringify({ version: 4, records: [copy] }), 'utf8')
    await app.evaluate(({ dialog }, filePath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filePath] }) }, importPath)
    await page.getByRole('button', { name: '导入备份', exact: true }).click()
    await page.getByRole('button', { name: '合并导入' }).click()
    await page.getByText('已导入 1 条新记录，跳过 0 条同编号记录。').waitFor()
    await page.locator('.record-list').getByRole('button', { name: /导入五模型副本/ }).click()
    assert.equal(await page.getByLabel('核心考点的达成性排序', { exact: true }).inputValue(), ranking)
    assert.equal(await page.getByLabel('模型4实际名称', { exact: true }).inputValue(), '自选模型甲')
    await page.waitForFunction(() => [...document.querySelectorAll('.image-preview img')].length === 5 && [...document.querySelectorAll('.image-preview img')].every(img => img.complete && img.naturalWidth > 0))
    await page.locator('#section-model4').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(root, 'test-results', 'five-models-desktop.png') })
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1120, 720))
    await page.locator('#section-ranking').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(root, 'test-results', 'five-models-narrow.png') })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    const model5Note = '关闭窗口前的最后一次修改。'
    await page.getByLabel('模型5达成性备注', { exact: true }).fill(model5Note)
    await page.locator('.save-indicator').click()
    await page.locator('.save-indicator.saved').waitFor()
    const closed = page.waitForEvent('close')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close()); await closed
    const savedData = await storage.load()
    assert.equal(savedData.records.find(value => value.id === copy.id).models.model5.note, model5Note)
    await app.close()
    app = await electron.launch(options); page = await app.firstWindow()
    await page.getByPlaceholder('记录标题').waitFor()
    await page.locator('.record-list').getByRole('button', { name: /导入五模型副本/ }).click()
    assert.equal(await page.getByLabel('模型5达成性备注', { exact: true }).inputValue(), model5Note)
    assert.equal(await page.getByLabel('核心考点的达成性排序说明', { exact: true }).inputValue(), explanation)
    assert.deepEqual(errors, [])
    console.log('v2 retained fields preserved, cancelled fields absent; all five replies copy exact Markdown; screenshots and ties persist through backup/import and restart.')
  } finally { await app.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
