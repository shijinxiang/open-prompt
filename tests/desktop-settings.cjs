const { _electron: electron } = require('playwright')
const path = require('path')
const fs = require('fs/promises')
const assert = require('node:assert/strict')

async function main() {
  const root = path.resolve(__dirname, '..')
  const dataDir = path.join(root, 'test-results', 'settings-data')
  await fs.rm(dataDir, { recursive: true, force: true })
  const env = { ...process.env, OQS_TEST_DATA: dataDir, OQS_USE_BUILD: '1' }
  delete env.ELECTRON_RUN_AS_NODE
  const options = { args: [root], executablePath: path.join(root, 'node_modules', 'electron', 'dist', 'electron.exe'), env }
  let app = await electron.launch(options)
  try {
    let page = await app.firstWindow()
    await page.locator('.main-workspace').waitFor()
    await page.locator('header').getByRole('button', { name: '新建记录' }).click()
    await page.locator('.record-item-missing').waitFor()
    const initialMissing = await page.locator('.record-item-missing').innerText()
    assert.match(initialMissing, /缺失 18 项/)
    assert.equal(await page.getByLabel('豆包专家实际名称', { exact: true }).inputValue(), '豆包专家')
    assert.equal(await page.getByLabel('豆包专家模式', { exact: true }).count(), 0)
    assert.equal(await page.getByLabel('问题（Prompt）').evaluate(element => getComputedStyle(element).fontSize), '14px')
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByLabel('字号数值').fill('20')
    await page.getByRole('button', { name: '黑夜模式', exact: true }).click()
    await page.locator('.settings-save-status.saved').waitFor()
    assert.equal(await page.getByLabel('问题（Prompt）').evaluate(element => getComputedStyle(element).fontSize), '20px')
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
    await page.screenshot({ path: path.join(root, 'test-results', 'settings-max.png') })
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click()
    await page.locator('.missing-notice summary').click()
    const missingText = await page.locator('.missing-fields').innerText()
    assert.match(missingText, /豆包专家 · 原始回复/)
    assert.match(missingText, /GPT-5.6-Sol · 截图/)
    assert.match(missingText, /核心考点/)
    await page.getByPlaceholder('记录标题').fill('缺失资料仍可保存')
    await page.getByLabel('问题类型', { exact: true }).selectOption('How-to 类')
    await page.getByLabel('问题（Prompt）').fill('问题正文')
    await page.getByLabel('关键洞察（Insight）').fill('关键洞察')
    await page.getByLabel('决定性核心考点', { exact: true }).fill('整段考点')
    await page.getByLabel('验收结果', { exact: true }).selectOption('不通过')
    await page.locator('.save-indicator').click()
    await page.locator('.save-indicator.saved').waitFor()
    assert.match(await page.locator('.record-item-missing').innerText(), /缺失 12 项/)
    const first = JSON.parse(await fs.readFile(path.join(dataDir, 'records.json'), 'utf8'))
    assert.equal(first.records[0].title, '缺失资料仍可保存')
    const image = { name: 'shot.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j2HsAAAAASUVORK5CYII=', 'base64') }
    for (const [id, model] of [['doubao', '豆包专家'], ['gpt', 'GPT-5.6-Sol'], ['opus', 'Opus 4.6']]) {
      assert.equal(await page.getByLabel(`${model}实际名称`, { exact: true }).inputValue(), model)
      assert.equal(await page.getByLabel(`${model}模式`, { exact: true }).count(), 0)
      await page.getByLabel(`${model}原始回复`, { exact: true }).fill('回复正文')
      await page.getByLabel(`${model}总体结果`, { exact: true }).selectOption('未达成')
      await page.getByLabel(`${model}达成性备注`, { exact: true }).fill('备注')
      await page.locator(`#section-${id} input[type=file]`).setInputFiles(image)
      await page.locator(`#section-${id} .image-preview img`).waitFor()
    }
    await page.locator('.complete-notice').waitFor()
    assert.equal(await page.locator('.record-item-missing').count(), 0)
    assert.equal(await page.locator('.record-item-complete').innerText(), '资料完整')
    assert.equal(await page.locator('.record-item-missing').count(), 0)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1120, 720))
    await page.locator('.detail-scroll').evaluate(element => { element.style.scrollBehavior = 'auto'; element.scrollTop = 0 })
    await page.screenshot({ path: path.join(root, 'test-results', 'settings-narrow.png') })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    const closed = page.waitForEvent('close')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close())
    await closed
    assert.deepEqual(JSON.parse(await fs.readFile(path.join(dataDir, 'settings.json'), 'utf8')), { fontSize: 20, theme: 'dark' })
    await app.close()
    app = await electron.launch(options)
    page = await app.firstWindow()
    await page.getByLabel('问题（Prompt）').waitFor()
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.prompt-input')).fontSize === '20px')
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
    assert.equal(await page.locator('.record-item-missing').count(), 0)
    await page.getByRole('button', { name: '设置', exact: true }).click()
    assert.equal(await page.getByLabel('字号数值').inputValue(), '20')
    await page.getByRole('button', { name: '恢复默认字号', exact: true }).click()
    await page.locator('.settings-save-status.saved').waitFor()
    assert.equal(await page.getByLabel('字号数值').inputValue(), '14')
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
    await page.getByRole('button', { name: '白天模式', exact: true }).click()
    await page.locator('.settings-save-status.saved').waitFor()
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'light')
    await page.screenshot({ path: path.join(root, 'test-results', 'theme-light.png') })
    console.log('Font size and theme live updates and restart persistence; missing reminders remain nonblocking.')
  } finally { await app.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
